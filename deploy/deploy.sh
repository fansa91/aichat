#!/usr/bin/env bash
# aichat 一键部署脚本（流程沿用 liuying）
#
#   ./deploy.sh --download [--dir /opt/aichat] [--port 3002] [--user root]
#               [--db-host 127.0.0.1] [--db-port 3306] [--db-user aichat]
#               [--db-pass secret] [--db-name aichat] [--key-encryption-key <64hex>]
#   ./deploy.sh --web-dist /path/aichat-web-dist.tar.gz --api-dist /path/aichat-api-dist.tar.gz [...]
#
# 流程：解压 web/dist 与 api/dist → 写 api/.env（merge-only，不覆盖手工改动，0600）
#       → 由模板生成 systemd 单元 → daemon-reload + enable + restart。
# 注意：Caddy 不由本脚本改动，按 deploy/Caddyfile 手工接入。
set -euo pipefail

DIR="/opt/aichat"
PORT="3002"
RUN_USER="root"
NODE="$(command -v node || true)"
REPO="fansa91/aichat"
TAG="latest"
DOWNLOAD=0
WEB_DIST=""
API_DIST=""
DB_HOST=""; DB_PORT=""; DB_USER=""; DB_PASS=""; DB_NAME=""
KEY_ENC=""

usage() {
  echo "Usage: $0 [--download | --web-dist F --api-dist F] [options]"
  echo "Options: --dir --port --user --node --repo --tag"
  echo "         --db-host --db-port --db-user --db-pass --db-name --key-encryption-key"
  exit 1
}

while [ $# -gt 0 ]; do
  case "$1" in
    --download) DOWNLOAD=1; shift ;;
    --web-dist) WEB_DIST="$2"; shift 2 ;;
    --api-dist) API_DIST="$2"; shift 2 ;;
    --dir) DIR="$2"; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    --user) RUN_USER="$2"; shift 2 ;;
    --node) NODE="$2"; shift 2 ;;
    --repo) REPO="$2"; shift 2 ;;
    --tag) TAG="$2"; shift 2 ;;
    --db-host) DB_HOST="$2"; shift 2 ;;
    --db-port) DB_PORT="$2"; shift 2 ;;
    --db-user) DB_USER="$2"; shift 2 ;;
    --db-pass) DB_PASS="$2"; shift 2 ;;
    --db-name) DB_NAME="$2"; shift 2 ;;
    --key-encryption-key) KEY_ENC="$2"; shift 2 ;;
    *) usage ;;
  esac
done

[ -z "$NODE" ] && { echo "node not found, pass --node"; exit 1; }
if [ "$DOWNLOAD" -eq 1 ]; then
  command -v curl >/dev/null || { echo "curl not found"; exit 1; }
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  base="https://github.com/${REPO}/releases/download/${TAG}"
  echo "downloading from $base ..."
  curl -fsSL -o "$tmp/web.tar.gz" "$base/aichat-web-dist.tar.gz"
  curl -fsSL -o "$tmp/api.tar.gz" "$base/aichat-api-dist.tar.gz"
  WEB_DIST="$tmp/web.tar.gz"
  API_DIST="$tmp/api.tar.gz"
fi
[ -z "$WEB_DIST" ] || [ -z "$API_DIST" ] && usage
[ -f "$WEB_DIST" ] || { echo "missing $WEB_DIST"; exit 1; }
[ -f "$API_DIST" ] || { echo "missing $API_DIST"; exit 1; }

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$DIR/web" "$DIR/api"

echo "extracting web -> $DIR/web/dist"
rm -rf "$DIR/web/dist"
mkdir -p "$DIR/web/dist"
tar -xzf "$WEB_DIST" -C "$DIR/web/dist"

echo "extracting api -> $DIR/api"
rm -rf "$DIR/api/dist"
mkdir -p "$DIR/api"
tar -xzf "$API_DIST" -C "$DIR/api"
# 依赖：tarball 自带 node_modules；缺失时尝试在线安装
if [ ! -d "$DIR/api/node_modules" ]; then
  echo "node_modules missing, running npm ci --omit=dev ..."
  (cd "$DIR/api" && "$NODE" "$(command -v npm)" ci --omit=dev --no-audit --no-fund)
fi
# 补齐 migrations（如缺失则警告）
if [ ! -d "$DIR/api/migrations" ]; then
  echo "WARNING: $DIR/api/migrations missing, DB migrations will not run"
fi

# ---- api/.env（merge-only，保留手工改动） ----
ENV_FILE="$DIR/api/.env"
declare -A envmap
if [ -f "$ENV_FILE" ]; then
  while IFS='=' read -r k v; do
    [[ "$k" =~ ^#.*$ ]] && continue
    [ -z "$k" ] && continue
    envmap["$k"]="$v"
  done < "$ENV_FILE"
fi
setkv() { # setkv KEY VALUE（VALUE 为空则跳过）
  if [ -n "${2:-}" ]; then envmap["$1"]="$2"; fi
}
setkv PORT "$PORT"
setkv DB_HOST "$DB_HOST"; setkv DB_PORT "$DB_PORT"
setkv DB_USER "$DB_USER"; setkv DB_PASSWORD "$DB_PASS"; setkv DB_NAME "$DB_NAME"
if [ -n "$KEY_ENC" ]; then
  setkv AICHAT_KEY_ENCRYPTION_KEY "$KEY_ENC"
elif [ -z "${envmap[AICHAT_KEY_ENCRYPTION_KEY]:-}" ]; then
  gen="$(node -e "console.log(require('crypto').randomBytes(32).toString('hex'))")"
  envmap["AICHAT_KEY_ENCRYPTION_KEY"]="$gen"
  echo "generated random AICHAT_KEY_ENCRYPTION_KEY (stored in $ENV_FILE, keep it safe)"
fi
{
  echo "# generated by deploy.sh on $(date -u +%FT%TZ); manual edits preserved"
  for k in PORT DB_HOST DB_PORT DB_USER DB_PASSWORD DB_NAME AICHAT_KEY_ENCRYPTION_KEY; do
    v="${envmap[$k]:-}"
    # 去掉换行，防注入
    v="${v//$'\n'/}"
    echo "$k=$v"
  done
  # 保留未知键
  for k in "${!envmap[@]}"; do
    case "$k" in
      PORT|DB_HOST|DB_PORT|DB_USER|DB_PASSWORD|DB_NAME|AICHAT_KEY_ENCRYPTION_KEY) ;;
      *) echo "$k=${envmap[$k]}" ;;
    esac
  done
} > "$ENV_FILE"
chmod 600 "$ENV_FILE"
echo "wrote $ENV_FILE"

# ---- systemd 单元 ----
UNIT_SRC="$SCRIPT_DIR/aichat-api.service"
UNIT_DST="/etc/systemd/system/aichat-api.service"
sed -e "s|@DIR@|$DIR|g" -e "s|@USER@|$RUN_USER|g" -e "s|@NODE@|$NODE|g" "$UNIT_SRC" > "$UNIT_DST"
systemctl daemon-reload
systemctl enable --now aichat-api.service
systemctl restart aichat-api.service
sleep 2
systemctl --no-pager --lines=5 status aichat-api.service || true
echo "deploy done: web=$DIR/web/dist api=127.0.0.1:$PORT"
